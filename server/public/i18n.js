const I18N_ALL = { ru: I18N_RU, uk: I18N_UK };
const I18N = I18N_ALL[LANG] || {};

const fillIn = (s, args) => (args.length ? s.replace(/\{(\d+)\}/g, (m, i) => (i < args.length ? String(args[i]) : m)) : s);
const hasEntry = (dict, text) => !!dict && Object.prototype.hasOwnProperty.call(dict, text);

function tl(text, ...args) {
  return fillIn(hasEntry(I18N, text) ? I18N[text] : text, args);
}

function tlIn(lang, text, ...args) {
  if (lang === 'en') return fillIn(text, args);
  const dict = I18N_ALL[lang];
  return fillIn(hasEntry(dict, text) ? dict[text] : hasEntry(I18N, text) ? I18N[text] : text, args);
}

let i18nPatterns = null;
function tlMsg(message) {
  const m = String(message ?? '');
  if (LANG === 'en' || Object.prototype.hasOwnProperty.call(I18N, m)) return tl(m);
  if (!i18nPatterns) {
    const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    i18nPatterns = Object.keys(I18N).filter((k) => /\{\d+\}/.test(k)).map((k) => {
      const order = [];
      const re = esc(k).replace(/\\\{(\d+)\\\}/g, (x, i) => { order.push(+i); return '(.+?)'; });
      return { k, order, re: new RegExp('^' + re + '$', 's') };
    });
  }
  for (const p of i18nPatterns) {
    const r = p.re.exec(m);
    if (!r) continue;
    const args = [];
    p.order.forEach((i, j) => { args[i] = r[j + 1]; });
    return tl(p.k, ...args);
  }
  return m;
}

function tn(n, forms) {
  const f = tl(forms).split('|');
  let i;
  if (f.length === 3) {
    const a = Math.abs(n) % 100, b = a % 10;
    i = a > 10 && a < 20 ? 2 : b === 1 ? 0 : b >= 2 && b <= 4 ? 1 : 2;
  } else i = n === 1 ? 0 : 1;
  return (f[i] ?? f[f.length - 1]).replace(/\{0\}/g, String(n));
}

function i18nDom(root) {
  document.documentElement.lang = LANG;
  document.documentElement.style.setProperty('--running-label', JSON.stringify(' — ' + tl('running…')));
  if (LANG === 'en') return;
  const has = (s) => Object.prototype.hasOwnProperty.call(I18N, s);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  for (let n = walker.currentNode; n; n = walker.nextNode()) {
    if (n.nodeType === Node.TEXT_NODE) {
      const t = n.nodeValue.trim();
      if (t && has(t)) n.nodeValue = n.nodeValue.replace(t, I18N[t]);
    } else {
      if (n.tagName === 'SCRIPT' || n.tagName === 'STYLE') continue;
      for (const a of ['title', 'placeholder', 'aria-label', 'alt', 'label']) {
        const v = n.getAttribute(a);
        if (v && has(v)) n.setAttribute(a, I18N[v]);
      }
    }
  }
}
